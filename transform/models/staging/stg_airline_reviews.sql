SELECT
    REVIEW_ID AS review_id,
    AIRLINE_ID AS airline_id,
    CAST(VERIFY AS BOOLEAN) AS is_verified,
    CAST(DATE_SUBMITTED AS DATE) AS date_submitted,
    CAST(DATE_FLOWN AS DATE) AS date_flown,
    NULLIF(TRIM(CUSTOMER_NAME), '') AS customer_name,
    NULLIF(TRIM(NATIONALITY), '') AS nationality,
    NULLIF(TRIM(TYPE_OF_TRAVELLER), '') AS type_of_traveller,
    NULLIF(TRIM(SEAT_TYPE), '') AS seat_type,
    NULLIF(TRIM(AIRCRAFT), '') AS aircraft,
    NULLIF(TRIM(ORIGIN_CITY), '') AS origin_city,
    NULLIF(TRIM(ORIGIN_AIRPORT), '') AS origin_airport,
    NULLIF(TRIM(DESTINATION_CITY), '') AS destination_city,
    NULLIF(TRIM(DESTINATION_AIRPORT), '') AS destination_airport,
    NULLIF(TRIM(TRANSIT_CITY), '') AS transit_city,
    NULLIF(TRIM(TRANSIT_AIRPORT), '') AS transit_airport,
    NULLIF(TRIM(REVIEW), '') AS review_text,
    NULLIF(SEAT_COMFORT, 0) AS seat_comfort,
    NULLIF(CABIN_STAFF_SERVICE, 0) AS cabin_staff_service,
    NULLIF(FOOD_AND_BEVERAGES, 0) AS food_and_beverages,
    NULLIF(INFLIGHT_ENTERTAINMENT, 0) AS inflight_entertainment,
    NULLIF(GROUND_SERVICE, 0) AS ground_service,
    NULLIF(WIFI_AND_CONNECTIVITY, 0) AS wifi_and_connectivity,
    NULLIF(VALUE_FOR_MONEY, 0) AS value_for_money,
    CAST(RECOMMENDED AS INTEGER) AS is_recommended,
    UPDATED_AT AS updated_at
FROM {{ source('skytrax_raw', 'RAW_AIRLINE_REVIEWS') }}
