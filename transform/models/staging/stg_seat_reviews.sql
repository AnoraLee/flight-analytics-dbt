SELECT
    REVIEW_ID AS review_id,
    AIRLINE_ID AS airline_id,
    NULLIF(TRIM(TYPE_OF_TRAVELLER), '') AS type_of_traveller,
    NULLIF(TRIM(SEAT_TYPE), '') AS seat_type,
    NULLIF(TRIM(AIRCRAFT_TYPE), '') AS aircraft_type,
    NULLIF(TRIM(SEAT_LAYOUT), '') AS seat_layout,
    CAST(VERIFY AS BOOLEAN) AS is_verified,
    CAST(DATE_SUBMITTED AS DATE) AS date_submitted,
    CAST(DATE_FLOWN AS DATE) AS date_flown,
    NULLIF(TRIM(CUSTOMER_NAME), '') AS customer_name,
    NULLIF(TRIM(NATIONALITY), '') AS nationality,
    NULLIF(TRIM(REVIEW), '') AS review_text,
    NULLIF(SEAT_LEGROOM, 0) AS seat_legroom,
    NULLIF(SEAT_RECLINE, 0) AS seat_recline,
    NULLIF(SEAT_WIDTH, 0) AS seat_width,
    NULLIF(AISLE_SPACE, 0) AS aisle_space,
    NULLIF(SEAT_STORAGE, 0) AS seat_storage,
    NULLIF(POWER_SUPPLY, 0) AS power_supply,
    NULLIF(VIEWING_TV_SCREEN, 0) AS viewing_tv_screen,
    NULLIF(SLEEP_COMFORT, 0) AS sleep_comfort,
    NULLIF(SITTING_COMFORT, 0) AS sitting_comfort,
    NULLIF(SEAT_BED_WIDTH, 0) AS seat_bed_width,
    NULLIF(SEAT_BED_LENGTH, 0) AS seat_bed_length,
    NULLIF(SEAT_PRIVACY, 0) AS seat_privacy,
    CAST(RECOMMENDED AS INTEGER) AS is_recommended,
    UPDATED_AT AS updated_at
FROM {{ source('skytrax_raw', 'RAW_SEAT_REVIEWS') }}
